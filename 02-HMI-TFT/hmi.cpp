// ZONAS TACTILES ACTIVAS (definidas por cada pantalla, btn = lo que se
// manda de vuelta al ESP32; debe coincidir exacto con lo que main.cpp espera)
struct BotonUI { int x, y, w, h, btn; };
BotonUI botones[4];
int numBotones = 0;

void limpiarBotones() { numBotones = 0; }

void agregarBoton(int x, int y, int w, int h, int btn, uint16_t colorFondo, uint16_t colorTexto, const char* texto) {
  botones[numBotones].x = x; botones[numBotones].y = y;
  botones[numBotones].w = w; botones[numBotones].h = h;
  botones[numBotones].btn = btn;
  numBotones++;

  tft.fillRect(x, y, w, h, colorFondo);
  tft.drawRect(x, y, w, h, WHITE);
  tft.setTextColor(colorTexto);
  tft.setTextSize(2);

  int16_t x1, y1;
  uint16_t textW, textH;
  tft.getTextBounds(texto, 0, 0, &x1, &y1, &textW, &textH);
  tft.setCursor(x + (w - textW) / 2, y + (h - textH) / 2);
  tft.print(texto);
}


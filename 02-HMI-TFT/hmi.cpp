// SETUP
void setup() {
  Serial.begin(9600); // hacia el ESP32 (Serial2 del otro lado), sin debug USB en paralelo

  uint16_t ID = tft.readID();
  if (ID == 0xD3D3) ID = 0x9341;
  tft.begin(ID);
  tft.setRotation(1);

  dibujarReposo(); // pantalla local de arranque, se corrige apenas llegue la respuesta
  Serial.println(F("SYNC")); // pide el estado real al ESP32 (por si ya venia en otra pantalla)
}

// LOOP PRINCIPAL
void loop() {
  TSPoint p = ts.getPoint();
  pinMode(XM, OUTPUT);
  pinMode(YP, OUTPUT);

  if (p.z > MINPRESSURE && p.z < MAXPRESSURE) {
    if (millis() - ultimoToque > DEBOUNCE_MS) {
      ultimoToque = millis();
      int touchX = map(p.y, TS_MINY, TS_MAXY, 320, 0);
      int touchY = map(p.x, TS_MINX, TS_MAXX, 240, 0);
      procesarToque(touchX, touchY);
    }
  }

  leerSerialESP32();
}

// TOQUES -> se manda el boton, el ESP32 decide que hacer
void procesarToque(int x, int y) {
  for (int i = 0; i < numBotones; i++) {
    BotonUI &b = botones[i];
    if (x >= b.x && x <= b.x + b.w && y >= b.y && y <= b.y + b.h) {
      enviarToque(b.btn);
      return;
    }
  }
}

void enviarToque(int btn) {
  Serial.print(F("TOQUE:"));
  Serial.println(btn);
}

// LECTURA SERIAL DEL ESP32 (sin String, para no fragmentar el heap del Uno)
void leerSerialESP32() {
  static char buf[48];
  static uint8_t idx = 0;

  while (Serial.available() > 0) {
    char c = Serial.read();
    if (c == '\n') {
      buf[idx] = '\0';
      procesarLinea(buf);
      idx = 0;
    } else if (c != '\r' && idx < sizeof(buf) - 1) {
      buf[idx++] = c;
    }
  }
}

void procesarLinea(char* linea) {
  if (strncmp(linea, "EST:", 4) == 0) {
    char* resto = linea + 4;
    char* tok = strtok(resto, ":");
    if (tok == nullptr) return;

    if (strcmp(tok, "REPOSO") == 0) {
      if (pantallaActual != P_REPOSO) { pantallaActual = P_REPOSO; dibujarReposo(); }

    } else if (strcmp(tok, "QR_ESPERA") == 0) {
      if (pantallaActual != P_QR_ESPERA) { pantallaActual = P_QR_ESPERA; dibujarQrEspera(); }

    } else if (strcmp(tok, "QR_PAGANDO") == 0) {
      if (pantallaActual != P_QR_PAGANDO) { pantallaActual = P_QR_PAGANDO; dibujarQrPagando(); }

    } else if (strcmp(tok, "PAGO_EXITOSO") == 0) {
      gProd = atoi(strtok(NULL, ":"));
      gVol  = atoi(strtok(NULL, ":"));
      gCosto = atoi(strtok(NULL, ":"));
      if (pantallaActual != P_PAGO_EXITOSO) { pantallaActual = P_PAGO_EXITOSO; dibujarPagoExitoso(); }

    } else if (strcmp(tok, "MONEDA_INGRESO") == 0) {
      gSaldo = atoi(strtok(NULL, ":"));
      if (pantallaActual != P_MONEDA_INGRESO) { pantallaActual = P_MONEDA_INGRESO; dibujarMonedaIngreso(); }

    } else if (strcmp(tok, "SEL_PROD") == 0) {
      gSaldo = atoi(strtok(NULL, ":"));
      char* mask = strtok(NULL, ":");
      if (mask != nullptr) strncpy(gMascara, mask, 3);
      if (pantallaActual != P_SEL_PROD) { pantallaActual = P_SEL_PROD; dibujarSelProd(); }

    } else if (strcmp(tok, "SEL_VOL") == 0) {
      gProd  = atoi(strtok(NULL, ":"));
      gSaldo = atoi(strtok(NULL, ":"));
      if (pantallaActual != P_SEL_VOL) { pantallaActual = P_SEL_VOL; dibujarSelVol(); }

    } else if (strcmp(tok, "CONFIRMACION") == 0) {
      gProd  = atoi(strtok(NULL, ":"));
      gVol   = atoi(strtok(NULL, ":"));
      gCosto = atoi(strtok(NULL, ":"));
      gSaldo = atoi(strtok(NULL, ":"));
      if (pantallaActual != P_CONFIRMACION) { pantallaActual = P_CONFIRMACION; dibujarConfirmacion(); }

    } else if (strcmp(tok, "DISPENSANDO") == 0) {
      if (pantallaActual != P_DISPENSANDO) { pantallaActual = P_DISPENSANDO; dibujarDispensando(); }

    } else if (strcmp(tok, "FINALIZADO") == 0) {
      gCosto = atoi(strtok(NULL, ":"));
      if (pantallaActual != P_FINALIZADO) { pantallaActual = P_FINALIZADO; dibujarFinalizado(); }

    } else if (strcmp(tok, "SLEEP") == 0) {
      if (pantallaActual != P_SLEEP) { pantallaActual = P_SLEEP; dibujarSleep(); }

    } else if (strcmp(tok, "SALDO_INSUF") == 0) {
      dibujarSaldoInsuficiente(); // aviso puntual, no cambia de pantalla
    }
  } else if (strncmp(linea, "SALDO:", 6) == 0) {
    gSaldo = atoi(linea + 6);
    // Solo tiene sentido refrescar el saldo en estas 4 pantallas
    if (pantallaActual == P_MONEDA_INGRESO || pantallaActual == P_SEL_PROD ||
        pantallaActual == P_SEL_VOL || pantallaActual == P_CONFIRMACION) {
      redibujarPantallaActual();
    }
  }
}

void redibujarPantallaActual() {
  switch (pantallaActual) {
    case P_MONEDA_INGRESO: dibujarMonedaIngreso(); break;
    case P_SEL_PROD:       dibujarSelProd(); break;
    case P_SEL_VOL:        dibujarSelVol(); break;
    case P_CONFIRMACION:   dibujarConfirmacion(); break;
    default: break;
  }
}

